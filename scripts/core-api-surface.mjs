#!/usr/bin/env node

/**
 * core:api — the public-API snapshot rail for the staged core.
 *
 * WHY: the core barrel header rules that adding, renaming or re-typing an
 * export is a contract change that must ride an extension version bump, so
 * the dsh bridge's staging-pin check catches drift at pin time. A rule
 * without enforcement is a sticky note: a version-bump-forgetting commit
 * passes the entire gauntlet by design. This rail makes an unintended API
 * move fail `npm run build` with the changed export named.
 *
 * HOW: the TypeScript checker resolves every export of `out/core/index.d.ts`
 * to its HOME declaration and prints it through the canonical printer —
 * comment-free, canonically formatted, sorted by export name. Comments and
 * formatting therefore never trip the rail; signatures, members, optionality
 * and shapes always do. Determinism: same tree, same TypeScript, same bytes.
 *
 * Known blind spots, accepted deliberately (the ack step is one command):
 *  - A member change inside a type that is NOT exported but referenced by an
 *    exported signature stays invisible here — the snapshot prints the type
 *    NAME. Consumers can still see such a shape via inference; export the
 *    type when its shape matters to a companion (then it gets a block).
 *  - A TypeScript upgrade can re-format canonical printer output and trip
 *    the rail with no API move. `--update` in the TS-bump unit is the answer.
 *  - Parameter RENAMES trip the rail although positional calls survive them —
 *    overly strict on purpose: names are documentation consumers read.
 *
 * Usage:
 *   node scripts/core-api-surface.mjs            -> compare, exit 1 on drift
 *   node scripts/core-api-surface.mjs --update   -> rewrite docs/core-api.txt
 *
 * Updating the snapshot IS the acknowledgment step of the API discipline:
 * run --update only when the move is intentional, and let it ride a version
 * bump in the same unit (dsh-vllm-bridge repo, docs/dsh-bridge-plan.md, Companion API rulings).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'out', 'core', 'index.d.ts');
const snapshotFile = join(root, 'docs', 'core-api.txt');
const update = process.argv.includes('--update');

if (!existsSync(entry)) {
  console.error(`core:api: ${entry} is missing — run \`npm run compile\` first.`);
  process.exit(1);
}

const program = ts.createProgram([entry], {
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  target: ts.ScriptTarget.ES2022,
  lib: ['lib.es2022.d.ts'],
  types: ['node'],
  strict: true,
  skipLibCheck: false,
});
const checker = program.getTypeChecker();
// removeComments is load-bearing twice: the snapshot promises comment-free
// output (docs must never trip the rail), and the export-keyword strip below
// anchors at the text start — kept comments would hide it.
const printer = ts.createPrinter({ removeComments: true });

const entrySource = program.getSourceFile(entry);
const moduleSymbol = entrySource && checker.getSymbolAtLocation(entrySource);
if (!moduleSymbol) {
  console.error('core:api: no module symbol for the core entry — declaration tree broken?');
  process.exit(1);
}

/** One `name => canonical declaration text` block per public export. */
function surface() {
  const blocks = new Map();
  for (const alias of checker.getExportsOfModule(moduleSymbol)) {
    const name = alias.getName();
    const symbol = checker.getAliasedSymbol(alias);
    const declarations = symbol?.getDeclarations() ?? [];
    if (declarations.length === 0) {
      blocks.set(name, '  <no declaration found>');
      continue;
    }
    const rendered = declarations.map((decl) => {
      const text = printer.printNode(ts.EmitHint.Unspecified, decl, decl.getSourceFile()).trim();
      // Normalize the home file's export keyword away: the snapshot describes
      // the surface of THIS module, not how the home file chooses to expose it.
      return `  ${text.replace(/^export\s+declare\s+/, '').replace(/^export\s+/, '').replace(/\n/g, '\n  ')}`;
    });
    blocks.set(name, rendered.join('\n'));
  }
  return blocks;
}

function serialize(blocks) {
  const lines = [
    '# GENERATED by `npm run core:api -- --update` — never hand-edit.',
    '# The public API surface of the staged core (exports of out/core/index.d.ts,',
    '# canonical printer output, sorted). Drift fails `npm run build`: an export',
    '# added, renamed or re-typed is a contract change for staged consumers and',
    '# must ride an extension version bump in the same unit. Re-run --update only',
    '# as the acknowledgment step of that discipline (dsh-vllm-bridge repo, docs/dsh-bridge-plan.md).',
    '',
  ];
  for (const name of [...blocks.keys()].sort()) {
    lines.push(`## ${name}`, blocks.get(name), '');
  }
  return lines.join('\n');
}

const fresh = serialize(surface());
const current = existsSync(snapshotFile) ? readFileSync(snapshotFile, 'utf8') : '';

if (update) {
  writeFileSync(snapshotFile, fresh);
  console.log(`core:api: snapshot rewritten (${fresh.split('\n## ').length - 1} exports) — commit it with the version bump.`);
  process.exit(0);
}

if (fresh === current) {
  console.log('core:api: public API surface matches docs/core-api.txt');
  process.exit(0);
}

// Name the offenders instead of dumping a wall of text: added/removed/changed
// exports are exactly the events the version law cares about.
const parse = (text) => {
  const blocks = new Map();
  let name = null;
  let body = [];
  for (const line of text.split('\n')) {
    if (line.startsWith('## ')) {
      if (name) blocks.set(name, body.join('\n'));
      name = line.slice(3);
      body = [];
    } else if (name && !line.startsWith('#')) {
      body.push(line);
    }
  }
  if (name) blocks.set(name, body.join('\n').trimEnd());
  return blocks;
};
const before = parse(current);
const after = parse(fresh);
const added = [...after.keys()].filter((n) => !before.has(n));
const removed = [...before.keys()].filter((n) => !after.has(n));
const changed = [...after.keys()].filter((n) => before.has(n) && before.get(n) !== after.get(n));
console.error('core:api: public API surface DRIFTED from docs/core-api.txt');
for (const n of added) console.error(`  + ${n}`);
for (const n of removed) console.error(`  - ${n}`);
for (const n of changed) console.error(`  ~ ${n}`);
console.error(
  'An export added/renamed/re-typed is a contract change for staged consumers:\n' +
  'it must ride an extension version bump (the bridge pins the version at staging).\n' +
  'If that is deliberate: `npm run core:api -- --update` and commit the snapshot\n' +
  'in the same unit as the bump. If it was an accident: you just dodged a pin-time\n' +
  'surprise for someone else\'s harness boot.'
);
process.exit(1);
